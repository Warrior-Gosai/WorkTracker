import React, { useEffect } from 'react';
import { useForm } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { X, FolderPlus, Edit3, ShieldCheck, Hash } from 'lucide-react';
import { projectSchema } from '../schemas/projectSchemas';
import Input from '../../../components/common/Input';
import Button from '../../../components/common/Button';

export const ProjectFormModal = ({
  isOpen,
  onClose,
  onSubmit,
  isLoading = false,
  project = null, // If provided, Edit mode; otherwise, Create mode
}) => {
  const isEditMode = Boolean(project);

  const {
    register,
    handleSubmit,
    reset,
    formState: { errors, isDirty },
  } = useForm({
    resolver: zodResolver(projectSchema),
    defaultValues: {
      projectName: '',
      description: '',
      remarks: '',
    },
  });

  useEffect(() => {
    if (project) {
      reset({
        projectName: project.projectName || '',
        description: project.description || '',
        remarks: project.remarks || '',
      });
    } else {
      reset({
        projectName: '',
        description: '',
        remarks: '',
      });
    }
  }, [project, reset, isOpen]);

  if (!isOpen) return null;

  const handleFormSubmit = async (values) => {
    await onSubmit(values);
  };

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto">
      {/* Backdrop */}
      <div
        className="fixed inset-0 bg-slate-900/50 backdrop-blur-sm transition-opacity"
        onClick={onClose}
      />

      <div className="min-h-full flex items-center justify-center p-4">
        <div className="relative bg-white rounded-xl shadow-xl border border-slate-200 w-full max-w-lg p-6 sm:p-7 overflow-hidden z-10 animate-in fade-in zoom-in-95 duration-150">
          {/* Header */}
          <div className="flex items-center justify-between pb-4 border-b border-slate-200">
            <div className="flex items-center space-x-3">
              <div
                className={`w-9 h-9 rounded-lg flex items-center justify-center ${
                  isEditMode
                    ? 'bg-amber-50 text-amber-600'
                    : 'bg-blue-50 text-blue-600'
                }`}
              >
                {isEditMode ? (
                  <Edit3 className="w-5 h-5" />
                ) : (
                  <FolderPlus className="w-5 h-5" />
                )}
              </div>
              <div>
                <h3 className="text-base font-bold text-slate-900">
                  {isEditMode ? 'Edit Project' : 'Create New Project'}
                </h3>
                <p className="text-xs text-slate-500">
                  {isEditMode
                    ? 'Update project title, description, and notes'
                    : 'Add a new client or internal development project'}
                </p>
              </div>
            </div>
            <button
              type="button"
              onClick={onClose}
              className="p-1.5 rounded-lg text-slate-400 hover:text-slate-600 hover:bg-slate-100 transition-colors"
              aria-label="Close dialog"
            >
              <X className="w-5 h-5" />
            </button>
          </div>

          {/* Read-only metadata in Edit Mode */}
          {isEditMode && (
            <div className="mt-4 p-3 bg-slate-50 rounded-lg border border-slate-200 flex items-center justify-between">
              <div className="flex items-center space-x-2">
                <Hash className="w-4 h-4 text-slate-400" />
                <span className="text-xs font-mono font-semibold text-slate-800">
                  {project.projectCode}
                </span>
              </div>
              <span
                className={`inline-flex items-center px-2 py-0.5 rounded-full text-xs font-medium ${
                  project.status === 1
                    ? 'bg-emerald-100 text-emerald-800'
                    : 'bg-slate-100 text-slate-600'
                }`}
              >
                {project.status === 1 ? 'Active' : 'Inactive'}
              </span>
            </div>
          )}

          {/* Notice in Create Mode */}
          {!isEditMode && (
            <div className="mt-4 p-3 bg-blue-50/60 rounded-lg border border-blue-100 flex items-start space-x-2.5">
              <ShieldCheck className="w-4 h-4 text-blue-600 flex-shrink-0 mt-0.5" />
              <p className="text-xs text-blue-800 leading-relaxed">
                Project Code is automatically generated by the database sequence (format: <code className="font-mono font-semibold">PRJ-000001</code>).
              </p>
            </div>
          )}

          {/* Form */}
          <form
            onSubmit={handleSubmit(handleFormSubmit)}
            className="mt-5 space-y-4"
            noValidate
          >
            <Input
              label="Project Name"
              name="projectName"
              type="text"
              required
              placeholder="e.g. Mobile Banking Application"
              helperText="Maximum 150 characters."
              error={errors.projectName?.message}
              {...register('projectName')}
            />

            <div>
              <label
                htmlFor="description"
                className="block text-sm font-medium text-slate-700 mb-1.5"
              >
                Description
              </label>
              <textarea
                id="description"
                rows={3}
                placeholder="High-level overview of project scope, objectives, or client background..."
                className="block w-full rounded-lg border border-slate-300 py-2.5 px-3.5 text-sm bg-white text-slate-900 placeholder-slate-400 focus:border-blue-600 focus:ring-1 focus:ring-blue-600 transition-colors"
                {...register('description')}
              />
              {errors.description && (
                <p className="mt-1.5 text-xs text-red-600 font-medium">
                  {errors.description.message}
                </p>
              )}
            </div>

            <div>
              <label
                htmlFor="remarks"
                className="block text-sm font-medium text-slate-700 mb-1.5"
              >
                Remarks
              </label>
              <textarea
                id="remarks"
                rows={2}
                placeholder="Internal notes, repository pointers, or environment notes..."
                className="block w-full rounded-lg border border-slate-300 py-2.5 px-3.5 text-sm bg-white text-slate-900 placeholder-slate-400 focus:border-blue-600 focus:ring-1 focus:ring-blue-600 transition-colors"
                {...register('remarks')}
              />
              {errors.remarks && (
                <p className="mt-1.5 text-xs text-red-600 font-medium">
                  {errors.remarks.message}
                </p>
              )}
            </div>

            {/* Actions */}
            <div className="pt-4 border-t border-slate-200 flex items-center justify-end space-x-3">
              <Button
                type="button"
                variant="secondary"
                size="md"
                onClick={onClose}
                disabled={isLoading}
              >
                Cancel
              </Button>
              <Button
                type="submit"
                variant="primary"
                size="md"
                isLoading={isLoading}
                disabled={isEditMode && !isDirty}
              >
                {isEditMode ? 'Save Changes' : 'Create Project'}
              </Button>
            </div>
          </form>
        </div>
      </div>
    </div>
  );
};

export default ProjectFormModal;

